fn missing() -> Glyph {
    pack(["#####", "#...#", "#.#.#", "#...#", "#.#.#", "#...#", "#####"])
}

fn glyph_for(ch: char) -> Glyph {
    if let Some(g) = ascii_glyph(ch) {
        return g;
    }
    if let Some(g) = cjk_map().get(&ch) {
        return *g;
    }
    // 全角数字等：仅当落在全角 ASCII 区间（0xFF01..=0xFF5E）才减偏移，避免下溢 panic
    if (0xFF01..=0xFF5E).contains(&(ch as u32)) {
        if let Some(ascii) = std::char::from_u32(ch as u32 - 0xFEE0) {
            if let Some(g) = ascii_glyph(ascii) {
                return g;
            }
        }
    }
    missing()
}

pub fn text_width(s: &str, scale: GlyphScale) -> i32 {
    let cell = 6 * scale as i32; // 5px + 1 gap
    s.chars().count() as i32 * cell
}

pub fn draw_text(img: &mut RgbImage, x: i32, y: i32, s: &str, color: Rgb<u8>, scale: GlyphScale) {
    let sc = scale as i32;
    let mut cx = x;
    let (iw, ih) = (img.width() as i32, img.height() as i32);
    for ch in s.chars() {
        let g = glyph_for(ch);
        for row in 0..7 {
            for col in 0..5 {
                if (g[row] >> (4 - col)) & 1 == 1 {
                    for dy in 0..sc {
                        for dx in 0..sc {
                            let px = cx + col * sc + dx;
                            let py = y + row as i32 * sc + dy;
                            if px >= 0 && py >= 0 && px < iw && py < ih {
                                img.put_pixel(px as u32, py as u32, color);
                            }
                        }
                    }
                }
            }
        }
        cx += 6 * sc;
    }
}
