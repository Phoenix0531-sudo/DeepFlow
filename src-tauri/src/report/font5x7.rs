use std::sync::OnceLock;

#[derive(Clone, Copy)]
pub enum GlyphScale {
    X2 = 2,
    X3 = 3,
    X4 = 4,
}

type Glyph = [u8; 7]; // 每行 5bit，高位在左

fn pack(rows: [&str; 7]) -> Glyph {
    let mut g = [0u8; 7];
    for (i, row) in rows.iter().enumerate() {
        let mut bits = 0u8;
        for (j, ch) in row.chars().take(5).enumerate() {
            if ch == '#' || ch == '1' {
                bits |= 1 << (4 - j);
            }
        }
        g[i] = bits;
    }
    g
}

